# gen.py <cfg.py>: builds the OLD / NEW input-path wrappers for the controllers.sv wave-2 equivalence test
# (CTL-2026-10-25). The OLD block is cut VERBATIM from the pre-integration backup of the top level, the NEW block from
# the live top level, by anchor lines (first line containing `start` .. first following line containing `end`;
# a third element 'excl' leaves the end line out).
# Every wrapper has the same ports (cfg PORTS) and output assign (cfg OUT). The intended differences are applied to the
# OLD text by scripted edits, each asserted to match exactly once:
#   k keyboard acts on press, s pad-2 Start = Start 2 only, t trackball dropped-step / opposite-D-pad fix,
#   p pause rule (library pause table), c core-specific intended change (Space Invaders trackball scaling)
# and written as old_in (none), old_<x> (one intent each), old_base (s + t + c: what must hold with pause off and no
# keyboard) and old_all (every intent). SUBMODS makes renamed, edited copies of old submodule files for an intent.
# Outputs (in this directory): old_in.sv (all old variants + OLD_EXTRA + SUBMODS copies), new_in.sv.
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
cfg = {}
exec(open(sys.argv[1]).read(), cfg)
INTENTS = 'kstpc'

def cut(path, start, end):
    lines = open(path, 'rb').read().decode('latin-1').replace('\r\n', '\n').split('\n')
    a = next(i for i, l in enumerate(lines) if start in l)
    b = next(i for i in range(a, len(lines)) if end in lines[i])
    return a + 1, b + 1, '\n'.join(lines[a:b + 1])

def body(path):
    out = []
    for ch in cfg['CHUNKS']:
        a, b, txt = cut(path, ch[0], ch[1])
        if len(ch) > 2 and ch[2] == 'excl':                 # end anchor line excluded
            b -= 1
            txt = txt.rsplit('\n', 1)[0]
        out.append('// ---- %s lines %d-%d\n%s' % (os.path.basename(path), a, b, txt))
    return '\n'.join(out)

def edit(txt, pairs, what):                                  # (a, b) = exactly once; (a, b, 'all') = at least once
    for e in pairs:
        a, b = e[0], e[1]
        n = txt.count(a)
        if len(e) > 2 and e[2] == 'all':
            assert n >= 1, '%s: anchor not found: %r' % (what, a)
        else:
            assert n == 1, '%s: anchor found %d times: %r' % (what, n, a)
        txt = txt.replace(a, b)
    return txt

def wrap(name, src):
    return ('/* verilator lint_off WIDTH */\n/* verilator lint_off UNUSED */\n/* verilator lint_off UNDRIVEN */\n'
            '/* verilator lint_off MULTIDRIVEN */\nmodule %s(\n%s\n);\n%s\n%s\nendmodule\n\n' % (name, cfg['PORTS'], src, cfg['OUT']))

E = cfg.get('EDITS', {})
old = edit(body(cfg['OLD_TOP']), cfg.get('PRE', []), 'PRE old')   # PRE: harness plumbing for both (e.g. drive a wire
new = edit(body(cfg['NEW_TOP']), cfg.get('PRE', []), 'PRE new')   # the region declares from a wrapper port)
variants = {'old_in': ''}
for x in INTENTS:
    variants['old_' + x] = x
variants['old_base'] = 'stc'
variants['old_all'] = INTENTS
txt = '// GENERATED by gen.py from %s - do not edit\n' % cfg['OLD_TOP']
for name, xs in variants.items():
    t = old
    for x in xs:
        t = edit(t, E.get(x, []), name + '/' + x)
    txt += wrap(name, t)
for (s, e) in cfg.get('OLD_EXTRA', []):
    a, b, t = cut(cfg['OLD_TOP'], s, e)
    txt += '// ---- %s lines %d-%d\n%s\n' % (os.path.basename(cfg['OLD_TOP']), a, b, t)
for (path, mod, newmod, pairs) in cfg.get('SUBMODS', []):
    t = open(path).read()
    t = edit(t, [('module ' + mod, 'module ' + newmod)] + pairs, newmod)
    txt += '// ---- %s as %s (scripted edits)\n%s\n' % (os.path.basename(path), newmod, t)
open(os.path.join(HERE, 'old_in.sv'), 'w').write(txt)
open(os.path.join(HERE, 'new_in.sv'), 'w').write('// GENERATED by gen.py from %s - do not edit\n' % cfg['NEW_TOP'] + wrap('new_in', new))
print('gen: old variants', ', '.join(variants), '| edits', {x: len(E.get(x, [])) for x in INTENTS})
